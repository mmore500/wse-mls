@app.function
def focal_sites_from_masks(mask_bytes) -> list:
    """Decode `flag_is_focal_mask_byte{B}` values into trait site indices.

    Bit `b` of byte `B` corresponds to trait site `B * 8 + b`, matching the
    `trait_num{B * 8 + b}` columns assigned during phylogeny build.
    """
    return [
        B * 8 + b
        for B, byte in enumerate(mask_bytes)
        for b in range(8)
        if int(byte) & (1 << b)
    ]


@app.function
def percentile_of_score_mean(
    values: np.ndarray, comparators: np.ndarray
) -> np.ndarray:
    """Vectorized `scipy.stats.percentileofscore(..., kind="mean")`.

    Ties are scored by mean rank, as in the clade-fitness screen of the
    reference ISAL 2025 multilevel selection work.
    """
    comparators = np.sort(np.asarray(comparators))
    values = np.asarray(values)
    left = np.searchsorted(comparators, values, side="left")
    right = np.searchsorted(comparators, values, side="right")
    return 50.0 * (left + right) / len(comparators)


@app.function
def bootstrap_p_value_mean_ge(
    values: np.ndarray,
    threshold: float,
    n_boot: int,
    rng: np.random.Generator,
    max_batch_elements: int = 2**26,
) -> float:
    """Fraction of bootstrap resample means at or above `threshold`.

    Small values indicate the population mean is below `threshold` (i.e.,
    MDC clades rank smaller/shorter-lived than comparators).
    """
    values = np.asarray(values, dtype=float)
    n = len(values)
    if n == 0:
        return np.nan

    batch_size = max(1, min(n_boot, max_batch_elements // n))
    successes = 0
    for begin in range(0, n_boot, batch_size):
        size = min(batch_size, n_boot - begin)
        idx = rng.integers(0, n, size=(size, n))
        successes += int(np.sum(values[idx].mean(axis=1) >= threshold))

    return successes / n_boot


