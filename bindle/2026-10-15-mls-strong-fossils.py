def _():
    def test_focal_sites_from_masks():
        assert focal_sites_from_masks([0] * 8) == []
        assert focal_sites_from_masks([0, 0, 0, 1, 0, 0, 0, 0]) == [24]
        assert focal_sites_from_masks([0b101, 0, 0, 0, 0, 0, 0, 0x80]) == [
            0,
            2,
            63,
        ]

    def test_percentile_of_score_mean():
        rng = np.random.default_rng(1)
        comparators = rng.integers(0, 10, size=50)
        values = rng.integers(-2, 12, size=20)
        expected = [
            scipy_stats.percentileofscore(comparators, v, kind="mean")
            for v in values
        ]
        np.testing.assert_allclose(
            percentile_of_score_mean(values, comparators), expected
        )

    def test_bootstrap_p_value_mean_ge():
        rng = np.random.default_rng(1)
        assert bootstrap_p_value_mean_ge(np.full(10, 10.0), 50, 100, rng) == 0
        assert bootstrap_p_value_mean_ge(np.full(10, 90.0), 50, 100, rng) == 1
        assert np.isnan(bootstrap_p_value_mean_ge(np.array([]), 50, 10, rng))
        p = bootstrap_p_value_mean_ge(
            np.arange(101.0), 50, 1000, rng, max_batch_elements=1000
        )
        assert 0.3 < p < 0.7

    return


