@app.cell
def prep_phylogeny(phylo_raw):
    phylo = phylo_raw.copy()
    phylo["extant"] = phylo["focal_trait_count"].notna() & (
        phylo["origin_time"] >= 0
    )
    phylo = pfl.alifestd_to_working_format(phylo, mutate=True)
    phylo = pfl.alifestd_prune_extinct_lineages_asexual(phylo, mutate=True)
    phylo = pfl.alifestd_collapse_unifurcations(phylo, mutate=True)
    phylo = pfl.alifestd_to_working_format(phylo, mutate=True)
    phylo = pfl.alifestd_mark_leaves(phylo, mutate=True)
    phylo = pfl.alifestd_mark_roots(phylo, mutate=True)
    phylo = pfl.alifestd_mark_num_leaves_asexual(phylo, mutate=True)
    phylo = pfl.alifestd_mark_clade_duration_asexual(phylo, mutate=True)
    assert (phylo["is_leaf"] == phylo["extant"]).all()
    phylo.reset_index(drop=True, inplace=True)
    return (phylo,)


